"""Generate independent binary-plist fixtures; no runtime reference dependency.

The base object is tools/bench/orangecar/carplay_receiver_sim.py
info_plist(1280, 720), whose audioFormats document the 2026-09-29 Jaguar capture.
"""
from copy import deepcopy
from pathlib import Path
import json
import plistlib

BASE = {
    "name": "Jaguar F-PACE", "model": "JLR,1", "manufacturer": "Jaguar",
    "deviceID": "aa:bb:cc:dd:ee:ff", "sourceVersion": "280.33.12.1",
    "keepAliveSendStatsAsBody": True,
    "audioFormats": [
        {"type": "100", "audioType": "compatibility", "audioInputFormats": "0x54", "audioOutputFormats": "0x854"},
        {"type": "101", "audioType": "compatibility", "audioOutputFormats": "0x8000"},
        {"type": "100", "audioType": "media", "audioOutputFormats": "0x8000"},
        {"type": "100", "audioType": "alert", "audioOutputFormats": "0x800"},
        {"type": "100", "audioType": "telephony", "audioInputFormats": "0x54", "audioOutputFormats": "0x54"},
        {"type": "100", "audioType": "speechRecognition", "audioInputFormats": "0x40", "audioOutputFormats": "0x40"},
        {"type": "100", "audioType": "default", "audioInputFormats": "0x50", "audioOutputFormats": "0x50"},
        {"type": "101", "audioType": "default", "audioOutputFormats": "0x800"},
    ],
    "audioLatencies": [{"type": 100, "audioType": "media", "inputLatencyMicros": 0, "outputLatencyMicros": 100000}],
    "displays": [{"widthPixels": 1280, "heightPixels": 720, "widthPhysical": 0,
                  "heightPhysical": 0, "maxFPS": 30, "features": 14,
                  "primaryInputDevice": 1, "uuid": "e5f7a5a0-0000-0000-0000-000000000001"}],
    "modes": {
        "appStates": [{"appStateID": 1, "speechMode": -1}, {"appStateID": 2, "state": False}, {"appStateID": 3, "state": False}],
        "resources": [{"resourceID": resource, "transferType": 1, "transferPriority": 100,
                       "takeConstraint": 100, "borrowConstraint": 100} for resource in (1, 2)],
    },
}


def generate():
    lines = ["/* Generated by tests/generate_legacy_audio_info_fixtures.py with plistlib. */",
             "#ifndef LEGACY_AUDIO_INFO_FIXTURES_H", "#define LEGACY_AUDIO_INFO_FIXTURES_H",
             "#include <stddef.h>", "#include <stdint.h>", ""]

    def emit(name, value):
        data = plistlib.dumps(value, fmt=plistlib.FMT_BINARY, sort_keys=True)
        lines.append("static const uint8_t " + name + "[] = {")
        for offset in range(0, len(data), 16):
            lines.append("    " + ",".join("0x%02x" % b for b in data[offset:offset + 16]) + ",")
        lines.extend(["};", ""])

    emit("jaguar_string_audio_info", BASE)
    for style in ("integer", "decimal"):
        variant = deepcopy(BASE)
        for audio in variant["audioFormats"]:
            for key in ("type", "audioInputFormats", "audioOutputFormats"):
                if key in audio:
                    number = int(audio[key], 0)
                    audio[key] = number if style == "integer" else str(number)
        emit("jaguar_" + style + "_audio_info", variant)

    cases = []

    def case(label, field, value, expected):
        entry = {"type": "100", "audioType": "telephony", "audioInputFormats": "0x40", "audioOutputFormats": "0x40"}
        entry[field] = value
        numbers = {"type": 100, "audioInputFormats": 64, "audioOutputFormats": 64}
        numbers[field] = expected
        name = "audio_number_case_%d" % len(cases)
        emit(name, {"audioFormats": [entry]})
        cases.append((label, name, numbers))

    invalid = ["", " ", "+32768", "-32768", "-0", " 32768", "32768 ", "\t32768",
               "32768\n", "32 768", "32768junk", "0x", "0X", "0x8000q", "0x+8000",
               "00x8000", "0b100", "0o100", "32768\0junk", "0x8000\0",
               "18446744073709551616", "0x10000000000000000", "4294967296", "0x100000000",
               True, b"32768", 32768.0, -1, 4294967296,
               "\u3332\u3736\u3830\u3030\u3030", "\u3078\u3430\u4141\u4141",
               "\u00a032768", "\uff13\uff12\uff17\uff16\uff18"]
    for index, value in enumerate(invalid):
        case("invalid output %d" % index, "audioOutputFormats", value, 0)
    for value, expected in [("0", 0), ("0X8000", 32768), ("032768", 32768),
                            ("0" * 40 + "32768", 32768), ("4294967295", 0xffffffff),
                            ("0xFFFFFFFF", 0xffffffff), (0xffffffff, 0xffffffff)]:
        case("valid output %d" % len(cases), "audioOutputFormats", value, expected)
    for value, expected in [("0x64", 100), ("0100", 100), ("+100", 0), ("100\0junk", 0),
                            ("2147483648", 0), ("4294967396", 0), (4294967396, 0), (-1, 0)]:
        case("type boundary %d" % len(cases), "type", value, expected)
    for value in ["0x100000040", "-64", "64 ", 0x100000040]:
        case("invalid input %d" % len(cases), "audioInputFormats", value, 0)

    geometry = deepcopy(BASE)
    geometry["displays"][0]["widthPixels"] = "1280"
    geometry["displays"][0]["heightPixels"] = "720"
    emit("jaguar_string_geometry_info", geometry)

    lines.extend(["struct legacy_audio_number_fixture {", "    const char *label;",
                  "    const uint8_t *data; size_t len;", "    int type; uint32_t output, input;", "};",
                  "static const struct legacy_audio_number_fixture legacy_audio_number_fixtures[] = {"])
    for label, name, numbers in cases:
        lines.append("    {%s, %s, sizeof(%s), %d, UINT32_C(0x%x), UINT32_C(0x%x)}," %
                     (json.dumps(label), name, name, numbers["type"], numbers["audioOutputFormats"], numbers["audioInputFormats"]))
    lines.extend(["};", ""])

    # Reconstruct the Audi masks and empty parsed classification logged on
    # 2026-11-15. Raw /info was not retained; absent and empty audioType are
    # tested separately rather than assuming which encoding the car used.
    def audio(kind=None, output=0x8010, input=0x10, stream=100):
        result = {"type": stream, "audioOutputFormats": output, "audioInputFormats": input}
        if kind is not None:
            result["audioType"] = kind
        return result

    selections = []

    def selection(label, entries, media=0x8000, call=0x10, enabled_media=1, enabled_mic=1):
        name = "audio_selection_case_%d" % len(selections)
        emit(name, {"audioFormats": entries})
        selections.append((label, name, enabled_media, enabled_mic, media, call))

    audi = [audio(), audio(output=0x10, stream=101)]
    selection("Audi unlabelled main and alternate audio", audi)
    selection("empty classification", [audio("")])
    selection("compatibility fallback", [audio("compatibility")])
    specific = [audio(), audio("media", 0x800, 0), audio("telephony", 0x40, 0x40)]
    selection("explicit classifications take precedence", specific, 0x800, 0x40)
    selection("explicit precedence independent of order", list(reversed(specific)), 0x800, 0x40)
    selection("unlabelled precedes compatibility", [audio("compatibility", 0x840, 0x40), audio()])
    selection("unsupported explicit media cannot widen", [audio(), audio("media", 0x800000, 0)], 0, 0x10)
    selection("explicit call has no bidirectional format", [audio(), audio("telephony", 0x10, 0x40)], 0x8000, 0)
    duplicates = [audio("media", 0x8000, 0), audio("media", 0x10, 0)]
    selection("duplicate media union", duplicates, 0x8000, 0)
    selection("duplicate media reversed", list(reversed(duplicates)), 0x8000, 0)
    selection("duplicates cannot fabricate duplex support",
              [audio("telephony", 0x10, 0x40), audio("telephony", 0x40, 0x10)], 0, 0)
    selection("unlabelled entries keep duplex pairs", [audio(output=0x8000, input=0), audio(output=0, input=0x8000)], 0x8000, 0)
    selection("alternate stream cannot supply main audio", [audio(stream=101)], 0, 0)
    selection("other uses are not media fallbacks", [audio("alert"), audio("default")], 0, 0)
    selection("unsupported generic formats", [audio(output=0x800000, input=0x800000)], 0, 0)
    selection("media disabled", audi, 0, 0x10, 0, 1)
    selection("microphone disabled", audi, 0x8000, 0, 1, 0)
    selection("both disabled", audi, 0, 0, 0, 0)
    for bad in (100, True, b"media", {"type": "media"}, "m" * 100,
                "\0media", "media\0junk", "\0", "\u6d65\u6469\u6100\u3030\u3030"):
        selection("invalid classification %d" % len(selections), [audio(bad)], 0, 0)
    selection("invalid classification cannot hide valid generic",
              [audio("media\0junk", 0x800, 0), audio()])
    selection("mixed case explicit labels", [audio("MEDIA", 0x800, 0), audio("Telephony", 0x40, 0x40)], 0x800, 0x40)

    lines.extend(["struct legacy_audio_selection_fixture {", "    const char *label;",
                  "    const uint8_t *data; size_t len;", "    int media_enabled, mic_enabled;",
                  "    uint32_t media_format, call_format;", "};",
                  "static const struct legacy_audio_selection_fixture legacy_audio_selection_fixtures[] = {"])
    for label, name, enabled_media, enabled_mic, media, call in selections:
        lines.append("    {%s, %s, sizeof(%s), %d, %d, UINT32_C(0x%x), UINT32_C(0x%x)}," %
                     (json.dumps(label), name, name, enabled_media, enabled_mic, media, call))
    lines.extend(["};", "#endif", ""])
    destination = Path(__file__).parent / "fixtures/legacy_audio_info_fixtures.h"
    destination.write_text("\n".join(lines), encoding="utf-8")
    print("generated Jaguar /info, %d numeric and %d audio selection fixtures" % (len(cases), len(selections)))


if __name__ == "__main__":
    generate()
