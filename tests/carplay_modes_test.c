#define APPLY(s, fixture) carplay_modes_apply((s), (fixture), sizeof(fixture))
#define REJECT(s, fixture) reject_unchanged((s), (fixture), sizeof(fixture))

static unsigned checks;

static void reject_unchanged(struct carplay_modes *s,
                             const unsigned char *body, size_t len)
{
    struct carplay_modes before = *s;
    assert(carplay_modes_apply(s, body, len) == -1);
    assert(memcmp(&before, s, sizeof(before)) == 0);
    const char *reason = NULL;
    assert(carplay_modes_apply_with_reason(s, body, len, &reason) == -1);
    assert(reason && *reason && memcmp(&before, s, sizeof(before)) == 0);
    checks++;
}

static void ownership(void)
{
    struct carplay_modes s;
    const char *reason = "stale";
    carplay_modes_init(&s, 1);
    assert(carplay_modes_apply_with_reason(&s, borrow_audio, sizeof(borrow_audio), &reason) == 0);
    assert(reason == NULL && s.audio_borrowed);
    carplay_modes_init(&s, 0);
    assert(carplay_modes_screen_active(&s));
    assert(!carplay_modes_audio_active(&s));
    assert(s.screen_entity == 1 && s.screen_permanent_entity == 1);
    assert(s.audio_entity == 2 && s.audio_permanent_entity == 2);
    REJECT(&s, unborrow_screen);
    REJECT(&s, unborrow_audio);
    assert(APPLY(&s, borrow_audio) == 0);
    assert(s.audio_entity == 2 && s.audio_permanent_entity == 2);
    assert(!carplay_modes_audio_active(&s));
    assert(APPLY(&s, unborrow_audio) == 0);
    assert(s.audio_entity == 2 && s.audio_permanent_entity == 2);
    assert(!carplay_modes_audio_active(&s));
    assert(APPLY(&s, borrow_screen) == 0);
    assert(!carplay_modes_screen_active(&s));
    assert(s.screen_entity == 2 && s.screen_permanent_entity == 1);
    assert(APPLY(&s, borrow_screen) == 0); /* Idempotent repeated Borrow. */
    assert(APPLY(&s, unborrow_screen) == 0);
    assert(carplay_modes_screen_active(&s));
    REJECT(&s, unborrow_screen);

    carplay_modes_init(&s, 1);
    assert(carplay_modes_audio_active(&s));
    assert(s.audio_entity == 1 && s.audio_permanent_entity == 1);
    assert(APPLY(&s, borrow_both) == 0);
    assert(!carplay_modes_screen_active(&s));
    assert(!carplay_modes_audio_active(&s));
    assert(s.screen_entity == 2 && s.screen_permanent_entity == 1);
    assert(s.audio_entity == 2 && s.audio_permanent_entity == 1);
    assert(APPLY(&s, unborrow_both) == 0);
    assert(carplay_modes_screen_active(&s));
    assert(carplay_modes_audio_active(&s));
    checks++;
}

static void atomic_rejections(void)
{
    struct carplay_modes s;
    carplay_modes_init(&s, 1);
    REJECT(&s, take);
    assert(APPLY(&s, untake) == 0); /* A late release cannot remove our ownership. */
    REJECT(&s, partial_take);
    REJECT(&s, partial_unknown);
    REJECT(&s, duplicate);
    REJECT(&s, missing_resources);
    REJECT(&s, empty);
    REJECT(&s, app_change);
    REJECT(&s, app_invalid);
    REJECT(&s, missing_type);
    REJECT(&s, wrong_type);
    REJECT(&s, missing_transfer);
    REJECT(&s, wrong_resources);
    REJECT(&s, bool_id);
    REJECT(&s, negative_id);
    REJECT(&s, wrong_transfer);
    REJECT(&s, duplicate_transfer_key);
    assert(APPLY(&s, app_empty) == 0);
    /* First Unborrow valid, second invalid: no partial release. */
    REJECT(&s, unborrow_both);
    assert(s.screen_entity == 2 && s.screen_borrowed);
    s.screen_entity = CARPLAY_ENTITY_NONE;
    REJECT(&s, borrow_screen); /* Invalid current state must fail closed. */
    checks++;
}

static void malformed(void)
{
    struct carplay_modes s;
    unsigned char copy[sizeof(borrow_both)];
    carplay_modes_init(&s, 1);
    for (size_t n = 0; n < sizeof(borrow_both); n++)
        reject_unchanged(&s, borrow_both, n);
    memcpy(copy, borrow_both, sizeof(copy));
    copy[9] = 0xff; /* Root key reference outside the object table. */
    reject_unchanged(&s, copy, sizeof(copy));
    memcpy(copy, borrow_both, sizeof(copy));
    copy[sizeof(copy) - 25] = 0; /* Invalid reference size. */
    reject_unchanged(&s, copy, sizeof(copy));
    reject_unchanged(&s, NULL, 0);
    assert(carplay_modes_apply(NULL, borrow_both, sizeof(borrow_both)) == -1);
    assert(!carplay_modes_screen_active(NULL));
    assert(!carplay_modes_audio_active(NULL));
    checks++;
}

static void save(const char *dir, const char *name,
                  const unsigned char *body, size_t len)
{
    char path[1024];
    FILE *file;
    if (!dir) return;
    assert(snprintf(path, sizeof(path), "%s/%s", dir, name) > 0);
    file = fopen(path, "wb");
    assert(file);
    assert(fwrite(body, 1, len, file) == len);
    assert(fclose(file) == 0);
}

