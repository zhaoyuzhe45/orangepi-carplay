#!/usr/bin/env python3
"""Regenerate src/airplay_screen_fixture.c from an Annex-B H.264 file.

The AirPlay screen channel carries length-prefixed (AVCC) NAL units plus a
separate AVCDecoderConfigurationRecord, so the Annex-B stream that ffmpeg emits
has to be repacked. Run this whenever the placeholder picture changes:

    ffmpeg -f lavfi -i "smptehdbars=size=1280x600:rate=1" -frames:v 1 \
        -vf "drawtext=fontfile=/path/to/font.ttf:text='...':x=(w-tw)/2:y=18:fontsize=40:fontcolor=white" \
        -c:v libx264 -profile:v baseline -level 3.1 -pix_fmt yuv420p -g 1 -bf 0 -crf 28 \
        -f h264 build/fixture/new.h264
    python3 tools/generate-screen-fixture.py build/fixture/new.h264 src/airplay_screen_fixture.c
"""

import pathlib
import sys

NAL_SPS = 7
NAL_PPS = 8
NAL_IDR = 5


def split_annexb(data):
    """Return the list of NAL payloads (without start codes)."""
    nals = []
    i = 0
    length = len(data)
    while i + 3 <= length:
        if data[i] == 0 and data[i + 1] == 0:
            if data[i + 2] == 1:
                start = i + 3
                i = start
            elif i + 4 <= length and data[i + 2] == 0 and data[i + 3] == 1:
                start = i + 4
                i = start
            else:
                i += 1
                continue
            end = data.find(b"\x00\x00\x01", start)
            if end < 0:
                end = length
            nal = data[start:end].rstrip(b"\x00")
            if nal:
                nals.append(nal)
            i = end
        else:
            i += 1
    return nals


def build_avcc(sps, pps):
    if len(sps) > 0xFFFF or len(pps) > 0xFFFF:
        raise ValueError("SPS/PPS too long for AVCDecoderConfigurationRecord")
    out = bytearray()
    out += bytes((1, sps[1], sps[2], sps[3], 0xFF, 0xE1))
    out += len(sps).to_bytes(2, "big")
    out += sps
    out += bytes((0x01,))
    out += len(pps).to_bytes(2, "big")
    out += pps
    return bytes(out)


def c_array(name, blob, indent="    ", per_line=12):
    lines = []
    for offset in range(0, len(blob), per_line):
        chunk = blob[offset:offset + per_line]
        lines.append(indent + " ".join("0x%02x," % b for b in chunk))
    body = "\n".join(lines)
    return "const uint8_t %s[] = {\n%s\n};\n" % (name, body)


def main():
    if len(sys.argv) != 3:
        print(__doc__.strip().splitlines()[0], file=sys.stderr)
        print("usage: generate-screen-fixture.py <in.h264> <out.c>", file=sys.stderr)
        return 2
    source = pathlib.Path(sys.argv[1])
    target = pathlib.Path(sys.argv[2])
    nals = split_annexb(source.read_bytes())
    sps = next((n for n in nals if n[0] & 0x1F == NAL_SPS), None)
    pps = next((n for n in nals if n[0] & 0x1F == NAL_PPS), None)
    idr = next((n for n in nals if n[0] & 0x1F == NAL_IDR), None)
    if not (sps and pps and idr):
        raise SystemExit("input is missing SPS, PPS or an IDR slice")

    # Keep every parameter-set and slice NAL that the decoder needs for the
    # first key frame; SEI and filler are dropped on purpose.
    config = build_avcc(sps, pps)
    frame = b"".join(len(nal).to_bytes(4, "big") + nal for nal in nals
                     if nal[0] & 0x1F in (NAL_SPS, NAL_PPS, NAL_IDR))

    text = [
        "/* Generated by tools/generate-screen-fixture.py -- do not edit by hand.\n"
        " *\n"
        " * H.264 placeholder the box sends over the AirPlay screen channel while no\n"
        " * real capture is available. Public builds use a neutral 800x480 display icon.\n"
        " * Normal screen capture is encoded at the negotiated receiver dimensions.\n"
        " */\n"
        "#include \"airplay_screen_fixture.h\"\n",
        "",
        c_array("airplay_screen_test_config", config),
        "const size_t airplay_screen_test_config_len = sizeof(airplay_screen_test_config);\n",
        "",
        c_array("airplay_screen_test_frame", frame),
        "const size_t airplay_screen_test_frame_len = sizeof(airplay_screen_test_frame);\n",
    ]
    target.write_text("\n".join(text))
    print("wrote %s: config=%d frame=%d bytes" % (target, len(config), len(frame)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
